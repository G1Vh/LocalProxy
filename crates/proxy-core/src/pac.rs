//! PAC file for Windows and browsers.
//!
//! Hosts that a rule sends to the outbound get `PROXY 127.0.0.1:<port>`,
//! everything else gets `DIRECT`, so unmatched traffic never touches LocalProxy.
//! The script mirrors [`RuleSet::decide`]: rules come pre-sorted by precedence
//! and the first match wins.

use crate::config::{MatchType, OnOutboundDown, RuleAction};
use crate::matcher::RuleSet;

pub const PAC_PATH: &str = "/proxy.pac";
pub const PAC_CONTENT_TYPE: &str = "application/x-ns-proxy-autoconfig";

pub fn generate(rules: &RuleSet, port: u16, on_down: OnOutboundDown) -> String {
    let entries: Vec<String> = rules
        .entries()
        .iter()
        .map(|r| {
            let kind = match r.match_type {
                MatchType::Exact => "e",
                MatchType::DomainAndSubdomains => "s",
                MatchType::Mask => "m",
            };
            let direct = u8::from(r.action == RuleAction::Direct);
            let pattern = serde_json::to_string(&r.pattern).expect("string serializes");
            format!("  [\"{kind}\", {pattern}, {direct}]")
        })
        .collect();

    // If LocalProxy is not running, "DIRECT" after the proxy lets the browser go
    // around it; with the block policy matched hosts must fail instead.
    let proxy = match on_down {
        OnOutboundDown::Block => format!("PROXY 127.0.0.1:{port}"),
        OnOutboundDown::Direct => format!("PROXY 127.0.0.1:{port}; DIRECT"),
    };

    format!(
        r#"// Generated by LocalProxy on every rule change. Do not edit.
// [type, pattern, direct]: e = exact, s = domain and subdomains, m = mask.
// Sorted by precedence: the first rule that matches decides.
var RULES = [
{rules}
];
var PROXY = "{proxy}";

function FindProxyForURL(url, host) {{
  host = host.toLowerCase();
  if (host.charAt(0) === "[") host = host.substring(1, host.length - 1);
  while (host.charAt(host.length - 1) === ".") host = host.substring(0, host.length - 1);
  for (var i = 0; i < RULES.length; i++) {{
    var t = RULES[i][0], p = RULES[i][1], hit;
    if (t === "e") {{
      hit = host === p;
    }} else if (t === "s") {{
      hit = host === p ||
        (host.length > p.length && host.substring(host.length - p.length - 1) === "." + p);
    }} else {{
      hit = shExpMatch(host, p);
    }}
    if (hit) return RULES[i][2] === 1 ? "DIRECT" : PROXY;
  }}
  return "DIRECT";
}}
"#,
        rules = entries.join(",\n"),
    )
}

/// Short content hash, used as `?v=` so Windows refetches a changed PAC
/// instead of serving its cached copy.
pub fn version(pac: &str) -> String {
    // FNV-1a: stable across Rust versions, unlike `DefaultHasher`.
    let hash = pac.bytes().fold(0xcbf29ce484222325u64, |h, b| {
        (h ^ u64::from(b)).wrapping_mul(0x100000001b3)
    });
    format!("{:08x}", hash >> 32)
}

#[cfg(test)]
mod tests {
    use std::process::Command;

    use uuid::Uuid;

    use super::*;
    use crate::config::Rule;

    fn rule(pattern: &str, match_type: MatchType, action: RuleAction) -> Rule {
        Rule {
            id: Uuid::new_v4(),
            enabled: true,
            pattern: pattern.into(),
            match_type,
            action,
            comment: String::new(),
            preset: None,
        }
    }

    fn sample_rules() -> RuleSet {
        use MatchType::*;
        use RuleAction::*;
        RuleSet::new(&[
            rule("openai.com", DomainAndSubdomains, Proxy),
            rule("corp.com", DomainAndSubdomains, Proxy),
            rule("intranet.corp.com", DomainAndSubdomains, Direct),
            rule("api.corp.com", Exact, Proxy),
            rule("cdn-*.example.net", Mask, Proxy),
            rule("node?.local", Mask, Proxy),
            rule("x.com", DomainAndSubdomains, Direct),
            rule("x.com", Exact, Proxy),
            rule("github.com", Exact, Proxy),
            rule("пример.рф", DomainAndSubdomains, Proxy),
            rule("10.1.2.3", Exact, Proxy),
        ])
    }

    const HOSTS: &[&str] = &[
        "openai.com",
        "api.openai.com",
        "notopenai.com",
        "openai.com.evil.net",
        "OpenAI.com.",
        "corp.com",
        "mail.corp.com",
        "intranet.corp.com",
        "wiki.intranet.corp.com",
        "api.corp.com",
        "cdn-1.example.net",
        "cdn-eu.west.example.net",
        "cdn.example.net",
        "node1.local",
        "node12.local",
        "x.com",
        "www.x.com",
        "github.com",
        "api.github.com",
        "xn--e1afmkfd.xn--p1ai",
        "www.xn--e1afmkfd.xn--p1ai",
        "10.1.2.3",
        "10.1.2.4",
        "example.org",
        "localhost",
    ];

    #[test]
    fn pac_lists_rules_in_precedence_order() {
        let pac = generate(&sample_rules(), 3128, OnOutboundDown::Block);
        let api = pac.find("\"api.corp.com\"").unwrap();
        let corp = pac.find("\"corp.com\"").unwrap();
        assert!(api < corp, "more specific rule must come first");
        assert!(pac.contains("var PROXY = \"PROXY 127.0.0.1:3128\";"));
        let pac = generate(&sample_rules(), 3128, OnOutboundDown::Direct);
        assert!(pac.contains("var PROXY = \"PROXY 127.0.0.1:3128; DIRECT\";"));
    }

    #[test]
    fn version_changes_with_content() {
        let a = generate(&sample_rules(), 3128, OnOutboundDown::Block);
        let b = generate(&sample_rules(), 3129, OnOutboundDown::Block);
        assert_eq!(version(&a), version(&a));
        assert_ne!(version(&a), version(&b));
        assert_eq!(version(&a).len(), 8);
    }

    /// Runs the generated PAC in Node with a browser-like `shExpMatch` and
    /// checks every host against the Rust matcher. Skipped without Node.
    #[test]
    fn pac_agrees_with_matcher() {
        let rules = sample_rules();
        let pac = generate(&rules, 3128, OnOutboundDown::Block);
        let harness = format!(
            r#"function shExpMatch(s, p) {{
  var re = "^" + p.replace(/[.+^${{}}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*").replace(/\?/g, ".") + "$";
  return new RegExp(re).test(s);
}}
{pac}
var hosts = {hosts};
console.log(JSON.stringify(hosts.map(function (h) {{ return FindProxyForURL("http://" + h + "/", h); }})));
"#,
            hosts = serde_json::to_string(HOSTS).unwrap(),
        );
        let dir = tempfile::tempdir().unwrap();
        let script = dir.path().join("pac-test.js");
        std::fs::write(&script, harness).unwrap();
        let output = match Command::new("node").arg(&script).output() {
            Ok(o) => o,
            Err(e) => {
                eprintln!("node not available, skipping PAC check: {e}");
                return;
            }
        };
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let results: Vec<String> = serde_json::from_slice(&output.stdout).unwrap();
        for (host, got) in HOSTS.iter().zip(results) {
            let expected = match rules.decide(host).action {
                RuleAction::Proxy => "PROXY 127.0.0.1:3128",
                RuleAction::Direct => "DIRECT",
            };
            assert_eq!(got, expected, "host {host}");
        }
    }
}
